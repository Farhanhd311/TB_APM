def t(key: str, lang: str = "id") -> str:
    """Get translation for a key. Falls back to Indonesian if key/lang not found."""
    entry = TRANSLATIONS.get(key)
    if entry:
        return entry.get(lang, entry.get("id", key))
    return key


def get_lang() -> str:
    """Get current language from session state (loads from DB on first access)."""
    import streamlit as st
    if "language" not in st.session_state:
        try:
            from utils.database import get_profile
            profile = get_profile()
            if profile and profile.get('language'):
                st.session_state.language = profile['language']
            else:
                st.session_state.language = "id"
        except Exception:
            st.session_state.language = "id"
    return st.session_state.language


def render_language_selector():
    """Render a language toggle in the sidebar. Returns current language."""
    import streamlit as st
    lang = get_lang()
    with st.sidebar:
        st.markdown("<hr style='border-color:#1D5C5C; margin:12px 0;'>", unsafe_allow_html=True)
        options = ["🇮🇩 Indonesia", "🇺🇸 English"]
        idx = 0 if lang == "id" else 1
        choice = st.selectbox("🌍 Bahasa / Language", options, index=idx, key="global_lang_selector")
        new_lang = "id" if "Indonesia" in choice else "en"
        if new_lang != lang:
            st.session_state.language = new_lang
            try:
                from utils.database import get_profile, save_profile
                profile = get_profile()
                if profile:
                    save_profile(
                        profile.get("name", "User"),
                        profile.get("gender", "Male"),
                        profile.get("age", 25),
                        profile.get("height", 170),
                        profile.get("weight", 70),
                        new_lang
                    )
            except Exception:
                pass
            st.rerun()
    return get_lang()
